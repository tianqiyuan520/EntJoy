    public static class BindingsGenerator
    {
        // DLL 分离后：生成代码（wrapper/adapter）编译进 NativeTranspiled.dll。
        // 核心 runtime（JobSystem 等）仍在 NativeDll.dll。
        private const string NativeLibraryName = "NativeTranspiled";

        public static string GenerateBindingsClass(
            IEnumerable<IMethodSymbol> methods,
            IEnumerable<INamedTypeSymbol> jobStructs,
            Compilation compilation)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            // job 结构含 NativeArray/NativeList（内含托管 DisposeSentinel）→ 托管类型。生成代码用
            // sizeof/取址/指针强转??job ??blittable 字段搬运/读到 native 侧，是验证过的安全模式；
            // CS8500（对托管类型取大??地址）为 false positive，按 Unity 生成 interop 代码惯例屏蔽??
            sb.AppendLine("#pragma warning disable CS8500");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Runtime.InteropServices;");
            sb.AppendLine("using System.Runtime.CompilerServices;");
            sb.AppendLine("using EntJoy.ECS;");
            sb.AppendLine("using EntJoy.ECS.JobSystem;");
            sb.AppendLine("using EntJoy.Collections;");
            sb.AppendLine("using EntJoy.JobSystem;");
            sb.AppendLine();
            sb.AppendLine("namespace NativeTranspiler.Bindings");
            sb.AppendLine("{");
            sb.AppendLine("    public static unsafe partial class NativeExports");
            sb.AppendLine("    {");
            sb.AppendLine("        public delegate void JobFuncDelegate(IntPtr context);");
            sb.AppendLine("        public delegate void BatchJobFuncDelegate(IntPtr context, int startIndex, int count);");
            sb.AppendLine("        public delegate void ChunkJobFuncDelegate(IntPtr context, ChunkJobData* chunkData);");
            sb.AppendLine("        public delegate void CleanupFuncDelegate(IntPtr context);");
            sb.AppendLine();

            var attrSymbol = compilation.GetTypeByMetadataName("NativeTranspiler.NativeTranspileAttribute");

            // GPU/CUDA 后端已拆分至 feature/gpu-offload 分支；dev 仅保留 Cpp/Ispc Job。
            var nativeJobs = jobStructs.ToList();

            // 1. 为每个 Job 结构体生成静态缓存的委托字段和函数指针。
            foreach (var jobStruct in nativeJobs)
            {
                GenerateStaticDelegateFields(sb, jobStruct, compilation);
            }

            // 2. 静态构造函数：初始化所有缓存的委托和函数指针。
            sb.AppendLine("        static NativeExports()");
            sb.AppendLine("        {");
            foreach (var jobStruct in nativeJobs)
            {
                GenerateStaticConstructorInitialization(sb, jobStruct, compilation);
            }
            // 注册 Job 字段显式写入器（chunk 路径 CreateChunkContextBlock 分发用）
            foreach (var jobStruct in nativeJobs)
            {
                if (ComputeJobFieldMarshal(jobStruct).explicitOk)
                {
                    sb.AppendLine($"            NativeJobScheduler.RegisterJobFieldWriter(typeof({jobStruct.ToDisplayString()}), (NativeJobScheduler.JobFieldWriter<{jobStruct.ToDisplayString()}>)WriteJobFields_{jobStruct.Name});");
                }
            }
            sb.AppendLine("        }");
            sb.AppendLine();

            // 3. 鏅€氭柟娉曠殑 DllImport 鍜?Wrapper锛堣嚜鍔ㄥ唴鑱?MT 閫夋嫨锛?
            foreach (var method in methods)
            {
                GenerateMethodDllImport(sb, method);
                bool useMT = HasUseISPC_MT(method, attrSymbol);
                if (useMT)
                {
                    GenerateMethodDllImportMT(sb, method);
                }
                GenerateMethodWrapper(sb, method, useMT);
            }

            // 4. Job 结构体的 DllImport 和 Schedule 方法。
            foreach (var jobStruct in nativeJobs)
            {
                GenerateJobDllImport(sb, jobStruct, compilation);
                GenerateJobScheduleMethod(sb, jobStruct, compilation);
            }

            // 4c. 显式 Job 字段写入器（chunk 路径 CreateChunkContextBlock 用）??
            //     Debug ??DisposeSentinel ??Job struct ??blittable ??裸拷贝布局不可靠，
            //     ??Job 生成类型化写入器，静态构造时注册??NativeJobScheduler 的注册表（EntJoy 侧）??
            if (nativeJobs.Count > 0)
            {
                foreach (var jobStruct in nativeJobs)
                    GenerateJobFieldWriterMethod(sb, jobStruct);
                sb.AppendLine();
            }

            sb.AppendLine(GenerateCleanupFactoryMethod());
            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine();

            // 5. Job 扩展方法（Schedule 和 Run）
            // 注意：IJobEntity 的 JobExtensions 由 ECS 生成器生成（路由到原生/托管路径）
            // 这里只为 IJobChunk/IJobParallelFor/IJobFor/IJob 生成
            var nonEntityJobs = nativeJobs.Where(j => !CppJobGenerator.IsEntityJob(j)).ToList();
            if (nonEntityJobs.Count > 0)
            {
                sb.AppendLine("public static partial class JobExtensions");
                sb.AppendLine("{");
                foreach (var jobStruct in nonEntityJobs)
                {
                    GenerateJobExtensionMethod(sb, jobStruct);
                    GenerateJobRunMethod(sb, jobStruct, compilation);
                }
                sb.AppendLine("}");
            }

            return sb.ToString();
        }

        private static bool HasUseISPC_MT(ISymbol symbol, INamedTypeSymbol? attrSymbol)
            => AttributeHelper.HasUseISPC_MT(symbol, attrSymbol);

        // ---------- 方法 DllImport ----------
        private static void GenerateMethodDllImport(StringBuilder sb, IMethodSymbol method)
        {
            var cppFunctionName = CppGenerator.GetCppFunctionName(method);
            var returnType = method.ReturnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var methodName = method.Name + "_Native";
            var parameters = BuildMethodDllImportParams(method);
            sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{cppFunctionName}\", CallingConvention = CallingConvention.Cdecl)]");
            sb.AppendLine($"        private static extern {returnType} {methodName}({string.Join(", ", parameters)});");
            sb.AppendLine();
        }

        private static void GenerateMethodDllImportMT(StringBuilder sb, IMethodSymbol method)
        {
            var cppFunctionName = CppGenerator.GetCppFunctionName(method) + "_mt";
            var returnType = method.ReturnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var methodName = method.Name + "_mt_Native";
            var parameters = BuildMethodDllImportParams(method);
            parameters.Add("int numTasks");
            sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{cppFunctionName}\", CallingConvention = CallingConvention.Cdecl)]");
            sb.AppendLine($"        private static extern {returnType} {methodName}({string.Join(", ", parameters)});");
            sb.AppendLine();
        }

        private static void GenerateMethodWrapper(StringBuilder sb, IMethodSymbol method, bool useMT)
        {
            var returnType = method.ReturnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var methodName = method.Name;
            var parameters = method.Parameters.Select(p => $"{GetCSharpParameterType(p)} {p.Name}");
            sb.AppendLine($"        public static {returnType} {methodName}({string.Join(", ", parameters)})");
            sb.AppendLine("        {");
            sb.AppendLine("            unsafe {");
            // 直调执行窗口：Begin 在调用前开窗口（当前线程泳道，事件驱动），
            // finally 确保无论异常与否都关闭窗口并上报共享时间线段??
            sb.AppendLine($"            ulong __dbgId = NativeJobScheduler.BeginDirectCall(\"{methodName}\", {(useMT ? "(uint)Environment.ProcessorCount" : "1u")});");
            sb.AppendLine("            try {");
            if (method.ReturnType.SpecialType != SpecialType.System_Void)
                sb.Append("                return ");
            else
                sb.Append("                ");

            if (useMT)
            {
                sb.Append($"{methodName}_mt_Native(");
                var args = BuildMethodCallArgs(method);
                args.Add("Environment.ProcessorCount");
                sb.Append(string.Join(", ", args));
            }
            else
            {
                sb.Append($"{methodName}_Native(");
                var args = BuildMethodCallArgs(method);
                sb.Append(string.Join(", ", args));
            }
            sb.AppendLine(");");
            sb.AppendLine("            }");
            sb.AppendLine("            finally { NativeJobScheduler.EndDirectCall(__dbgId); }");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        // ---------- Job 委托字段 ----------
        private static void GenerateStaticDelegateFields(StringBuilder sb, INamedTypeSymbol jobStruct, Compilation compilation)
        {
            bool isChunk = CppJobGenerator.IsChunkScheduledJob(jobStruct);
            bool isParallelFor = CppJobGenerator.IsParallelForJob(jobStruct);
            bool isFor = CppJobGenerator.IsForJob(jobStruct);

            if (isChunk)
            {
                if (CppJobGenerator.IsEntityJob(jobStruct))
                {
            // IJobEntity 统一走 Chunk 级调度（与 ISPC 路径一致）。
                    sb.AppendLine($"        private static readonly IntPtr s_{jobStruct.Name}_ChunkFuncPtr;");
                    sb.AppendLine($"        private static readonly IntPtr s_{jobStruct.Name}_ChunkRangeFuncPtr;");
                }
                else
                {
                    sb.AppendLine($"        private static readonly IntPtr s_{jobStruct.Name}_ChunkFuncPtr;");
                    sb.AppendLine($"        private static readonly IntPtr s_{jobStruct.Name}_ChunkRangeFuncPtr;");
                    var attrSym2 = AttributeHelper.GetAttributeSymbol(compilation);
                    bool isIspc2 = attrSym2 != null && AttributeHelper.GetBackendTarget(jobStruct, attrSym2) == NativeTranspiler.BackendTarget.Ispc;
                    if (!isIspc2)
                        sb.AppendLine($"        private static readonly IntPtr s_{jobStruct.Name}_ChunkEntityBatchFuncPtr;");
                }
                var requiredTypes = CppJobGenerator.CollectChunkNativeArrayTypes(jobStruct, compilation);
                string requiredIds = BuildRequiredComponentTypeIdsInitializer(requiredTypes);
                sb.AppendLine($"        private static readonly int[] s_{jobStruct.Name}_RequiredComponentTypeIds = {requiredIds};");
            }
            else if (isParallelFor || isFor)
            {
                sb.AppendLine($"        private static readonly BatchJobFuncDelegate s_{jobStruct.Name}_BatchFunc;");
                sb.AppendLine($"        private static readonly IntPtr s_{jobStruct.Name}_BatchFuncPtr;");
            }
            else
            {
                sb.AppendLine($"        private static readonly JobFuncDelegate s_{jobStruct.Name}_JobFunc;");
                sb.AppendLine($"        private static readonly IntPtr s_{jobStruct.Name}_JobFuncPtr;");
            }
            sb.AppendLine($"        private static readonly CleanupFuncDelegate s_{jobStruct.Name}_CleanupFunc;");
            sb.AppendLine($"        private static readonly IntPtr s_{jobStruct.Name}_CleanupFuncPtr;");
            sb.AppendLine();
        }

        private static void GenerateStaticConstructorInitialization(StringBuilder sb, INamedTypeSymbol jobStruct, Compilation compilation)
        {
            string jobTypeFullName = jobStruct.ToDisplayString();
            bool isParallelFor = CppJobGenerator.IsParallelForJob(jobStruct);
            bool isFor = CppJobGenerator.IsForJob(jobStruct);
            bool isChunk = CppJobGenerator.IsChunkScheduledJob(jobStruct);

            var executeMethod = jobStruct.GetMembers().OfType<IMethodSymbol>().First(m => m.Name == Config.Execute);
            var methodSyntax = SymbolHelper.GetMethodSyntax(executeMethod);
            bool hasMultiVersion = false;
            string boolFieldName = null;
            List<IFieldSymbol> boolFields = new List<IFieldSymbol>();

            var attrSymbol = compilation.GetTypeByMetadataName("NativeTranspiler.NativeTranspileAttribute");
            bool useMT = HasUseISPC_MT(jobStruct, attrSymbol);

            if (methodSyntax != null)
            {
                var semanticModel = compilation.GetSemanticModel(methodSyntax.SyntaxTree);
                var conditionalFields = NativeTranspileValidator.GetConditionalReadOnlyFields(jobStruct, semanticModel);
                boolFields = conditionalFields.Where(f => f.Type.SpecialType == SpecialType.System_Boolean).ToList();
                if (boolFields.Count > 0)
                {
                    hasMultiVersion = true;
                    boolFieldName = boolFields[0].Name;
                }
            }

            if (isChunk)
            {
                if (CppJobGenerator.IsEntityJob(jobStruct))
                {
            // IJobEntity 统一走 Chunk 级调度（与 ISPC 路径一致）。
                    sb.AppendLine($"            s_{jobStruct.Name}_ChunkFuncPtr = Get_{jobStruct.Name}_ChunkAdapterPtr();");
                    sb.AppendLine($"            s_{jobStruct.Name}_ChunkRangeFuncPtr = Get_{jobStruct.Name}_ChunkRangeAdapterPtr();");
                }
                else
                {
                    sb.AppendLine($"            s_{jobStruct.Name}_ChunkFuncPtr = Get_{jobStruct.Name}_ChunkAdapterPtr();");
                    sb.AppendLine($"            s_{jobStruct.Name}_ChunkRangeFuncPtr = Get_{jobStruct.Name}_ChunkRangeAdapterPtr();");
                    var attrSym2 = AttributeHelper.GetAttributeSymbol(compilation);
                    bool isIspc2 = attrSym2 != null && AttributeHelper.GetBackendTarget(jobStruct, attrSym2) == NativeTranspiler.BackendTarget.Ispc;
                    if (!isIspc2)
                        sb.AppendLine($"            s_{jobStruct.Name}_ChunkEntityBatchFuncPtr = Get_{jobStruct.Name}_ChunkEntityBatchAdapterPtr();");
                }
            }
            else if (isParallelFor || isFor)
            {
                if (useMT)
                {
            // MT（task 内部自己调度）仍用托管 delegate：原生 Adapter 只生成非 MT 变体。
                string mtSuffix = "_mt";

                sb.AppendLine($"            s_{jobStruct.Name}_BatchFunc = (IntPtr context, int startIndex, int count) =>");
                sb.AppendLine("            {");
                sb.AppendLine($"                var jobPtr = ({jobTypeFullName}*)context;");

                string batchArgs = BuildBatchCallArgs(jobStruct, "jobPtr");
                string batchArgsWithComma = string.IsNullOrEmpty(batchArgs) ? "" : ", " + batchArgs;
                if (hasMultiVersion)
                {
                    // 生成所??2^n ??bool 组合??if-else 链，??C++ 端命名一??
                    int totalVariants = 1 << boolFields.Count;
                    var boolVarNames = boolFields.Select(f => $"jobPtr->{f.Name}").ToList();

                    for (int mask = 0; mask < totalVariants; mask++)
                    {
                        var values = new List<bool>();
                        for (int i = 0; i < boolFields.Count; i++)
                            values.Add((mask & (1 << i)) != 0);

                        string suffix = "_" + string.Join("_", values.Select(v => v ? "true" : "false"));

                        bool isLast = (mask == totalVariants - 1);
                        if (mask == 0)
                        {
                            string condition = string.Join(" && ", boolFields.Select((f, i) => values[i] ? $"jobPtr->{f.Name}" : $"!jobPtr->{f.Name}"));
                            sb.AppendLine($"                if ({condition})");
                        }
                        else if (!isLast)
                        {
                            string condition = string.Join(" && ", boolFields.Select((f, i) => values[i] ? $"jobPtr->{f.Name}" : $"!jobPtr->{f.Name}"));
                            sb.AppendLine($"                else if ({condition})");
                        }
                        else
                        {
                            sb.AppendLine("                else");
                        }

                        sb.AppendLine($"                    {jobStruct.Name}_Execute_Batch{suffix}{mtSuffix}(startIndex, count{batchArgsWithComma});");
                    }
                }
                else
                {
                    sb.AppendLine($"                {jobStruct.Name}_Execute_Batch{mtSuffix}(startIndex, count{batchArgsWithComma});");
                }
                sb.AppendLine("            };");
                sb.AppendLine($"            s_{jobStruct.Name}_BatchFuncPtr = Marshal.GetFunctionPointerForDelegate(s_{jobStruct.Name}_BatchFunc);");
                }
                else
                {
                    // ??MT：调度器直接调原??_Execute_Adapter(context,start,count)（原生→原生），
                    // 消除托管 BatchFunc delegate ??原生→托管→原生 双重转换（每 tile ~3μs 开销）??
                    // 原生 Adapter ??CppJobGenerator 生成：同一套字段偏移解??/ UnsafeList 写回 / bool 变体分派??
                    sb.AppendLine($"            s_{jobStruct.Name}_BatchFuncPtr = Get_{jobStruct.Name}_Execute_AdapterPtr();");
                }
            }
            else
            {
                sb.AppendLine($"            s_{jobStruct.Name}_JobFunc = (IntPtr context) =>");
                sb.AppendLine("            {");
                sb.AppendLine($"                var jobPtr = ({jobTypeFullName}*)context;");
                var args = BuildJobExecuteArgsForPointer(jobStruct);
                sb.AppendLine($"                {jobStruct.Name}_Execute({string.Join(", ", args)});");
                sb.AppendLine("            };");
                sb.AppendLine($"            s_{jobStruct.Name}_JobFuncPtr = Marshal.GetFunctionPointerForDelegate(s_{jobStruct.Name}_JobFunc);");
            }

            sb.AppendLine($"            s_{jobStruct.Name}_CleanupFunc = (IntPtr context) =>");
            sb.AppendLine("            {");
            sb.AppendLine("                Marshal.FreeHGlobal(context);");
            sb.AppendLine("            };");
            sb.AppendLine($"            s_{jobStruct.Name}_CleanupFuncPtr = Marshal.GetFunctionPointerForDelegate(s_{jobStruct.Name}_CleanupFunc);");
            sb.AppendLine();
        }

        private static void GenerateJobDllImport(StringBuilder sb, INamedTypeSymbol jobStruct, Compilation compilation)
        {
            bool isChunk = CppJobGenerator.IsChunkScheduledJob(jobStruct);
            bool isParallelFor = CppJobGenerator.IsParallelForJob(jobStruct);
            bool isFor = CppJobGenerator.IsForJob(jobStruct);

            var attrSymbol = compilation.GetTypeByMetadataName("NativeTranspiler.NativeTranspileAttribute");
            bool useMT = HasUseISPC_MT(jobStruct, attrSymbol);

            if (isChunk)
            {
                if (CppJobGenerator.IsEntityJob(jobStruct))
                {
            // IJobEntity 统一走 Chunk 级调度。
                    var getterName = CppJobGenerator.GetAdapterPtrGetterName(jobStruct);
                    var rangeGetterName = CppJobGenerator.GetRangeAdapterPtrGetterName(jobStruct);
                    sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{getterName}\", CallingConvention = CallingConvention.Cdecl)]");
                    sb.AppendLine($"        private static extern IntPtr Get_{jobStruct.Name}_ChunkAdapterPtr();");
                    sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{rangeGetterName}\", CallingConvention = CallingConvention.Cdecl)]");
                    sb.AppendLine($"        private static extern IntPtr Get_{jobStruct.Name}_ChunkRangeAdapterPtr();");
                }
                else
                {
                    var getterName = CppJobGenerator.GetAdapterPtrGetterName(jobStruct);
                    var rangeGetterName = CppJobGenerator.GetRangeAdapterPtrGetterName(jobStruct);
                    var entityBatchGetterName = CppJobGenerator.GetEntityBatchAdapterPtrGetterName(jobStruct);
                    sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{getterName}\", CallingConvention = CallingConvention.Cdecl)]");
                    sb.AppendLine($"        private static extern IntPtr Get_{jobStruct.Name}_ChunkAdapterPtr();");
                    sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{rangeGetterName}\", CallingConvention = CallingConvention.Cdecl)]");
                    sb.AppendLine($"        private static extern IntPtr Get_{jobStruct.Name}_ChunkRangeAdapterPtr();");
                    var attrSym2 = AttributeHelper.GetAttributeSymbol(compilation);
                    bool isIspc2 = attrSym2 != null && AttributeHelper.GetBackendTarget(jobStruct, attrSym2) == NativeTranspiler.BackendTarget.Ispc;
                    if (!isIspc2)
                    {
                        sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{entityBatchGetterName}\", CallingConvention = CallingConvention.Cdecl)]");
                        sb.AppendLine($"        private static extern IntPtr Get_{jobStruct.Name}_ChunkEntityBatchAdapterPtr();");
                    }
                }
            }
            else if (isParallelFor || isFor)
            {
                var batchFuncName = CppJobGenerator.GetCppJobFunctionName(jobStruct, isBatch: true);
                var batchParams = BuildBatchJobDllImportParams(jobStruct);

                var executeMethod = jobStruct.GetMembers().OfType<IMethodSymbol>().First(m => m.Name == Config.Execute);
                var methodSyntax = SymbolHelper.GetMethodSyntax(executeMethod);
                bool hasMultiVersion = false;
                if (methodSyntax != null)
                {
                    var semanticModel = compilation.GetSemanticModel(methodSyntax.SyntaxTree);
                    var conditionalFields = NativeTranspileValidator.GetConditionalReadOnlyFields(jobStruct, semanticModel);
                    hasMultiVersion = conditionalFields.Any(f => f.Type.SpecialType == SpecialType.System_Boolean);
                }

                if (hasMultiVersion)
                {
                    sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{batchFuncName}_true\", CallingConvention = CallingConvention.Cdecl)]");
                    sb.AppendLine($"        public static extern void {jobStruct.Name}_Execute_Batch_true({string.Join(", ", batchParams)});");
                    sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{batchFuncName}_false\", CallingConvention = CallingConvention.Cdecl)]");
                    sb.AppendLine($"        public static extern void {jobStruct.Name}_Execute_Batch_false({string.Join(", ", batchParams)});");
                }
                else
                {
                    sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{batchFuncName}\", CallingConvention = CallingConvention.Cdecl)]");
                    sb.AppendLine($"        public static extern void {jobStruct.Name}_Execute_Batch({string.Join(", ", batchParams)});");
                }

                if (useMT)
                {
                    if (hasMultiVersion)
                    {
                        sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{batchFuncName}_true_mt\", CallingConvention = CallingConvention.Cdecl)]");
                        sb.AppendLine($"        private static extern void {jobStruct.Name}_Execute_Batch_true_mt({string.Join(", ", batchParams)});");
                        sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{batchFuncName}_false_mt\", CallingConvention = CallingConvention.Cdecl)]");
                        sb.AppendLine($"        private static extern void {jobStruct.Name}_Execute_Batch_false_mt({string.Join(", ", batchParams)});");
                    }
                    else
                    {
                        sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{batchFuncName}_mt\", CallingConvention = CallingConvention.Cdecl)]");
                        sb.AppendLine($"        private static extern void {jobStruct.Name}_Execute_Batch_mt({string.Join(", ", batchParams)});");
                    }
                }
                else
                {
                    // ??MT：声明原??Adapter 指针 Getter（调度器原生→原生直调路径）
                    var adapterGetterName = CppJobGenerator.GetAdapterPtrGetterName(jobStruct);
                    sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{adapterGetterName}\", CallingConvention = CallingConvention.Cdecl)]");
                    sb.AppendLine($"        private static extern IntPtr Get_{jobStruct.Name}_Execute_AdapterPtr();");
                }
            }
            else
            {
                var singleFuncName = CppJobGenerator.GetCppJobFunctionName(jobStruct);
                var singleParams = BuildJobDllImportParams(jobStruct);
                sb.AppendLine($"        [DllImport(\"{NativeLibraryName}\", EntryPoint = \"{singleFuncName}\", CallingConvention = CallingConvention.Cdecl)]");
                sb.AppendLine($"        public static extern void {jobStruct.Name}_Execute({string.Join(", ", singleParams)});");
            }
            sb.AppendLine();
        }

        // ---------- Job Schedule 方法 ----------
        private static void GenerateJobScheduleMethod(StringBuilder sb, INamedTypeSymbol jobStruct, Compilation compilation)
        {
            bool isChunk = CppJobGenerator.IsChunkScheduledJob(jobStruct);
            bool isParallelFor = CppJobGenerator.IsParallelForJob(jobStruct);
            bool isFor = CppJobGenerator.IsForJob(jobStruct);
            string jobTypeName = jobStruct.ToDisplayString();

            var attrSymbol = compilation.GetTypeByMetadataName("NativeTranspiler.NativeTranspileAttribute");
            bool useMT = HasUseISPC_MT(jobStruct, attrSymbol);

            var parameters = new List<string>();
            // Use 'ref' for the internal Schedule_XXX method (caller already has a reference)
            parameters.Add($"ref {jobTypeName} job");
            if (isChunk)
            {
                parameters.Add("QueryBuilder query");
            }
            else if (isParallelFor || isFor)
            {
                parameters.Add("int arrayLength");
            // IJobFor 也允许指定 innerBatchCount，保持接口统一。
                parameters.Add("int innerBatchCount = 0");
            }
            parameters.Add("JobHandle dependsOn = default");

            sb.AppendLine($"        public static JobHandle Schedule_{jobStruct.Name}({string.Join(", ", parameters)})");
            sb.AppendLine("        {");
            if (!isChunk)
            {
                // Debug ??NativeArray ??GC 引用（DisposeSentinel）→ Job struct ??blittable，裸拷贝布局不可靠；
                // 改为显式逐字段写入（??C++ Adapter 偏移一致），Debug/Release 均正确??
                var (marshalled, explicitOk, totalSize) = ComputeJobFieldMarshal(jobStruct);
                if (explicitOk)
                {
                    sb.AppendLine($"            int size = {totalSize};");
                    sb.AppendLine("            IntPtr nativePtr = Marshal.AllocHGlobal(size);");
                    sb.AppendLine("            byte* __dst = (byte*)nativePtr;");
                    EmitExplicitFieldWrites(sb, marshalled, "__dst", "job");
                    sb.AppendLine();
                }
                else
                {
                    // 含不支持字段（NativeList 等）：退回裸拷贝（Release 正确；Debug 由显式路径覆盖的场景外）
                    sb.AppendLine($"            int size = sizeof({jobTypeName});");
                    sb.AppendLine("            IntPtr nativePtr = Marshal.AllocHGlobal(size);");
                    sb.AppendLine("            void* originalPtr = Unsafe.AsPointer(ref job);");
                    sb.AppendLine("            Unsafe.CopyBlockUnaligned((void*)nativePtr, originalPtr, (uint)size);");
                    sb.AppendLine();
                }
            }

            if (isChunk)
            {
                sb.AppendLine("            var world = World.DefaultWorld ?? throw new InvalidOperationException(\"No active World found.\");");
                // 鎵€鏈?native IJobChunk 璧?EntityBatch 璺緞锛圲nity 椋庢牸锛夛紝
